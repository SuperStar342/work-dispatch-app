type LocaleSlot = { locale: Ref<Locale> }

function readLocale(): Locale {
  try {
    const saved = uni.getStorageSync(STORAGE_KEY)
    if (saved === 'en' || saved === 'zh') return saved
  } catch {
    /* storage unavailable during startup */
  }
  return 'zh'
}

function slot(): LocaleSlot {
  const g = globalThis as typeof globalThis & { __WD_LOCALE__?: LocaleSlot }
  if (!g.__WD_LOCALE__) g.__WD_LOCALE__ = { locale: ref<Locale>(readLocale()) }
  return g.__WD_LOCALE__
}

export const locale = slot().locale

export function t(key: string, vars?: Record<string, string | number>) {
  const pack = messages[slot().locale.value] || messages.zh
  let text = pack[key] ?? messages.zh[key] ?? key
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value))
    }
  }
  return text
}

function currentRoute() {
  try {
    if (typeof location !== 'undefined') {
      const matched = (location.hash || '').match(/pages\/[A-Za-z0-9_/-]+/)
      if (matched) return matched[0]
    }
  } catch {
    /* mini program / app */
  }
  try {
    const pages = typeof getCurrentPages === 'function' ? getCurrentPages() : []
    return (pages[pages.length - 1] as { route?: string } | undefined)?.route || ''
  } catch {
    return ''
  }
}

export function syncPageTitle() {
  const route = currentRoute()
  const key = routeTitle[route]
  if (!key) return
  const title = t(key)
  try {
    uni.setNavigationBarTitle({ title })
  } catch {
    /* page not ready */
  }
  if (typeof document !== 'undefined') document.title = title
}

function installTitleHook() {
  const g = globalThis as typeof globalThis & { __WD_TITLE_HOOK__?: boolean }
  if (g.__WD_TITLE_HOOK__) return
  g.__WD_TITLE_HOOK__ = true
  try {
    ;(['navigateTo', 'redirectTo', 'reLaunch', 'switchTab', 'navigateBack'] as const).forEach((name) => {
      uni.addInterceptor(name, {
        complete() {
          setTimeout(syncPageTitle, 0)
          setTimeout(syncPageTitle, 80)
        },
      })
    })
  } catch {
    g.__WD_TITLE_HOOK__ = false
  }
}

installTitleHook()

export function tx(raw?: string) {
  if (!raw) return ''
  return raw.startsWith('i18n:') ? t(raw.slice(5)) : raw
}

export function setLocale(next: Locale) {
  slot().locale.value = next
  try {
    uni.setStorageSync(STORAGE_KEY, next)
  } catch {
    /* ignore */
  }
  syncPageTitle()
}
